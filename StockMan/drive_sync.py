def get_credentials_file() -> Optional[str]:
    """Finds credentials.json or service_account.json in project root or data/."""
    candidates = [
        os.path.join(PROJECT_ROOT, "credentials.json"),
        os.path.join(DATA_DIR, "credentials.json"),
        os.path.join(PROJECT_ROOT, "service_account.json"),
        os.path.join(DATA_DIR, "service_account.json"),
    ]
    for c in candidates:
        if os.path.isfile(c):
            return c
    return None


def get_token_file() -> str:
    """Returns path for token.json to persist OAuth user sessions."""
    return os.path.join(PROJECT_ROOT, "token.json")


def get_drive_service(
    credentials_path: Optional[str] = None,
    token_path: Optional[str] = None,
):
    """
    Sets up and returns an authenticated Google Drive API service.
    Supports:
      1. OAuth 2.0 User Flow (credentials.json -> token.json).
      2. Service Account Flow (service_account.json).
    """
    if not GOOGLE_DRIVE_AVAILABLE:
        raise ImportError(
            "Google Drive client libraries not installed. Run: pip install google-api-python-client google-auth-oauthlib"
        )

    creds = None
    cred_file = credentials_path or get_credentials_file()
    tok_file = token_path or get_token_file()

    # 1. Try loading cached user OAuth token
    if tok_file and os.path.exists(tok_file):
        try:
            creds = Credentials.from_authorized_user_file(tok_file, SCOPES)
        except Exception as e:
            logger.warning(f"Could not load token from '{tok_file}': {e}")

    # 2. Check if valid or refreshable
    if creds and creds.valid:
        pass
    elif creds and creds.expired and creds.refresh_token:
        try:
            creds.refresh(Request())
            # Save refreshed token
            with open(tok_file, "w", encoding="utf-8") as token_out:
                token_out.write(creds.to_json())
            logger.info("Refreshed expired Google Drive OAuth token.")
        except Exception as e:
            logger.warning(
                f"Failed to refresh OAuth token: {e}. Re-authenticating..."
            )
            creds = None

    # 3. If still no valid creds, authenticate from credentials file
    if not creds:
        if not cred_file or not os.path.exists(cred_file):
            raise FileNotFoundError(
                f"Google Drive API credentials file not found.\n\n"
                f"Please place your 'credentials.json' (OAuth 2.0 Desktop Client) or "
                f"'service_account.json' into the project root:\n{PROJECT_ROOT}"
            )

        # Detect if credentials file is a Service Account or OAuth client
        is_service_account = False
        try:
            import json

            with open(cred_file, "r", encoding="utf-8") as jf:
                data = json.load(jf)
                if data.get("type") == "service_account":
                    is_service_account = True
        except Exception:
            pass

        if is_service_account:
            logger.info(
                f"Authenticating via Google Service Account '{cred_file}'..."
            )
            creds = service_account.Credentials.from_service_account_file(
                cred_file, scopes=SCOPES
            )
        else:
            logger.info(
                f"Initiating Google Drive OAuth 2.0 Desktop authentication with '{cred_file}'..."
            )
            flow = InstalledAppFlow.from_client_secrets_file(cred_file, SCOPES)
            creds = flow.run_local_server(port=0)

            # Save the credentials for subsequent runs
            try:
                with open(tok_file, "w", encoding="utf-8") as token_out:
                    token_out.write(creds.to_json())
                logger.info(f"OAuth token saved to '{tok_file}'.")
            except Exception as te:
                logger.warning(f"Could not save token to '{tok_file}': {te}")

    return build("drive", "v3", credentials=creds)


def get_or_create_drive_folder(service, folder_name: str = "Finance") -> str:
    """
    Finds or creates a folder with the given name on Google Drive.
    Returns the folder ID.
    """
    query = (
        f"mimeType = 'application/vnd.google-apps.folder' "
        f"and name = '{folder_name}' "
        f"and trashed = false"
    )
    response = (
        service.files()
        .list(q=query, spaces="drive", fields="files(id, name)")
        .execute()
    )
    files = response.get("files", [])

    if files:
        folder_id = files[0]["id"]
        logger.info(
            f"Found Google Drive folder '{folder_name}' (ID: {folder_id})."
        )
        return folder_id

    # Create the folder
    folder_metadata = {
        "name": folder_name,
        "mimeType": "application/vnd.google-apps.folder",
    }
    folder = (
        service.files().create(body=folder_metadata, fields="id").execute()
    )
    folder_id = folder.get("id")
    logger.info(
        f"Created Google Drive folder '{folder_name}' (ID: {folder_id})."
    )
    return folder_id


