def get_current_day_cycle_start(now: Optional[datetime] = None) -> datetime:
    """
    Returns the start datetime of the current 8:00 AM cycle.
    Each day's cycle begins at 8:00 AM and runs until 7:59:59 AM the next day.
    If current time is before 8:00 AM, the active cycle began yesterday at 8:00 AM.
    """
    if now is None:
        now = datetime.now()
    if now.time() < dtime(8, 0):
        cycle_date = (now - timedelta(days=1)).date()
    else:
        cycle_date = now.date()
    return datetime.combine(cycle_date, dtime(8, 0))


def should_prompt_user_today(
    state_file: str = STATE_FILE_PATH,
    excel_path: str = PORTFOLIO_EXCEL_PATH,
    now: Optional[datetime] = None,
) -> bool:
    """
    Determines if user should be prompted for Appetite & Cash.
    Requirement: Prompt only once a day (first time of the day starting from 8:00 AM).
    Returns True if user has NOT yet been prompted in the current 8:00 AM cycle, False otherwise.
    """
    if now is None:
        now = datetime.now()
    cycle_start = get_current_day_cycle_start(now)

    # 1. Check persistent state file
    if os.path.exists(state_file):
        try:
            with open(state_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            last_prompt_str = data.get("last_prompt_time")
            if last_prompt_str:
                last_dt = datetime.fromisoformat(last_prompt_str)
                if last_dt >= cycle_start:
                    logger.info(
                        f"Daily prompt already completed for current 8:00 AM cycle "
                        f"(last confirmed: {last_dt.strftime('%d-%b %I:%M %p')}, "
                        f"cycle start: {cycle_start.strftime('%d-%b %I:%M %p')})."
                    )
                    return False
        except Exception as e:
            logger.warning(
                f"Could not read startup state from '{state_file}': {e}"
            )

    # 2. Fallback check: StockMan_Portfolio.xlsx file modification time
    if os.path.exists(excel_path):
        try:
            mtime = os.path.getmtime(excel_path)
            last_dt = datetime.fromtimestamp(mtime)
            if last_dt >= cycle_start:
                logger.info(
                    f"Portfolio Excel file was updated today at {last_dt.strftime('%d-%b %I:%M %p')} "
                    f"(cycle start: {cycle_start.strftime('%d-%b %I:%M %p')}). Skipping prompt."
                )
                return False
        except Exception:
            pass

    return True


def record_startup_prompt_completed(
    appetite: float,
    cash: float,
    state_file: str = STATE_FILE_PATH,
    timestamp: Optional[datetime] = None,
) -> None:
    """Records that user confirmed the startup prompt for the current cycle."""
    if timestamp is None:
        timestamp = datetime.now()
    try:
        os.makedirs(
            os.path.dirname(os.path.abspath(state_file)), exist_ok=True
        )
        data = {
            "last_prompt_time": timestamp.isoformat(),
            "appetite": appetite,
            "cash": cash,
        }
        with open(state_file, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        logger.info(f"Recorded startup prompt completion in '{state_file}'.")
    except Exception as e:
        logger.warning(
            f"Could not record startup state to '{state_file}': {e}"
        )


