# Full Application Startup Sequence Orchestrator
# -----------------------------------------------------------------------------
_STARTUP_COMPLETED = False


def run_startup_sequence(
    parent: Optional[tk.Tk | tk.Toplevel] = None,
    interactive: bool = True,
    force: bool = False,
) -> Dict[str, Any]:
    """
    Executes the complete 5-step startup sequence:
      Step A (Read): Extract Appetite & Cash from StockMan_Portfolio.xlsx.
      Step B (Prompt): Show UI dialog to confirm/edit values (if interactive=True).
      Step C (Write): Update StockMan_Portfolio.xlsx with values & SQLite stocks.
      Step D (Drive Upload): Upload/overwrite StockMan_Portfolio.xlsx to Google Drive 'Finance' folder.
      Step E (Drive Download): Download latest 'Pick_of_the_day_' report to data/.

    Returns status summary dictionary:
      {
        'success': bool,
        'step': str,
        'appetite': float,
        'cash': float,
        'uploaded': bool,
        'downloaded_file': Optional[str],
        'error': Optional[str]
      }
    """
    global _STARTUP_COMPLETED
    if _STARTUP_COMPLETED and not force:
        logger.info("Startup sequence already completed for this session.")
        return {"success": True, "step": "Already Completed"}

    status: Dict[str, Any] = {
        "success": False,
        "step": "Init",
        "appetite": DEFAULT_APPETITE,
        "cash": DEFAULT_CASH,
        "uploaded": False,
        "downloaded_file": None,
        "error": None,
    }

    try:
        # Step A: Read from Excel
        status["step"] = "Step A (Read Excel)"
        appetite, cash = read_investment_parameters(PORTFOLIO_EXCEL_PATH)
        status["appetite"] = appetite
        status["cash"] = cash

        # Step B: Prompt User via Dialog (once a day: first run starting from 8:00 AM)
        prompt_needed = force or should_prompt_user_today()
        if interactive and prompt_needed:
            status["step"] = "Step B (Prompt User)"
            confirmed_values = prompt_startup_parameters_dialog(
                parent=parent,
                default_appetite=appetite,
                default_cash=cash,
            )
            if confirmed_values is not None:
                appetite, cash = confirmed_values
                status["appetite"] = appetite
                status["cash"] = cash
                record_startup_prompt_completed(appetite, cash)
            else:
                logger.info("Startup sequence skipped by user during dialog.")
                status["step"] = "Skipped"
                status["success"] = True
                _STARTUP_COMPLETED = True
                return status
        else:
            logger.info(
                "Step B: Skipping prompt dialog (already answered for today's 8:00 AM cycle)."
            )

        # Step C: Write to Excel & SQLite population
        if prompt_needed:
            status["step"] = "Step C (Write Excel)"
            update_portfolio_excel(
                excel_path=PORTFOLIO_EXCEL_PATH,
                current_appetite=appetite,
                cash_available=cash,
                db_path=STOCK_DB_PATH,
            )
        else:
            logger.info(
                "Step C: Excel write skipped (parameters already set today)."
            )

        # Connect to Drive (Steps D & E)
        if not GOOGLE_DRIVE_AVAILABLE:
            msg = "google-api-python-client or google-auth-oauthlib not installed. Skipping Drive sync."
            logger.warning(msg)
            status["error"] = msg
            status["step"] = "Drive Unavailable"
            return status

        cred_file = get_credentials_file()
        if not cred_file:
            msg = "Google Drive credentials.json not found. Offline Excel updated; skipping Drive sync."
            logger.info(msg)
            status["error"] = msg
            status["step"] = "Drive Credentials Missing"
            status["success"] = True
            return status

        # Authenticate
        drive_service = get_drive_service()

        # Step D: Upload StockMan_Portfolio.xlsx to Drive
        if prompt_needed:
            status["step"] = "Step D (Drive Upload)"
            upload_res = upload_portfolio_to_drive(
                drive_service, PORTFOLIO_EXCEL_PATH, folder_name="Finance"
            )
            status["uploaded"] = True
            logger.info(f"Drive Upload successful: {upload_res}")
        else:
            logger.info(
                "Step D: Drive upload skipped (already uploaded in current cycle)."
            )

        # Step E: Download latest Pick_of_the_day_ report (silently ensures fresh local cache)
        status["step"] = "Step E (Drive Download)"
        download_res = download_latest_pick_of_the_day(
            drive_service, folder_name="Finance", dest_dir=DATA_DIR
        )
        if download_res:
            status["downloaded_file"] = download_res[0]
            logger.info(f"Drive Download successful: {download_res}")
        else:
            logger.info(
                "No Pick_of_the_day_ file found in Drive 'Finance' folder yet."
            )

        status["success"] = True
        status["step"] = "Complete"
        _STARTUP_COMPLETED = True
        return status

    except Exception as e:
        logger.error(
            f"Error during startup sequence at '{status['step']}': {e}",
            exc_info=True,
        )
        status["error"] = str(e)
        return status
