# Step B: User Prompt Dialog
# -----------------------------------------------------------------------------
def prompt_startup_parameters_dialog(
    parent: Optional[tk.Tk | tk.Toplevel] = None,
    default_appetite: float = DEFAULT_APPETITE,
    default_cash: float = DEFAULT_CASH,
) -> Optional[Tuple[float, float]]:
    """
    Step B:
    Prompts user via a modal dialog to review and edit 'Current Appetite' and
    'Cash Available for Investment', pre-filled with the values extracted in Step A.
    Returns (confirmed_appetite, confirmed_cash), or None if skipped/cancelled.
    """
    owns_root = False
    if parent is None:
        owns_root = True
        root = tk.Tk()
        root.withdraw()
        dialog_parent = root
    else:
        dialog_parent = parent

    dialog = tk.Toplevel(dialog_parent)
    dialog.title("Investment Parameters — StockMan")
    dialog.geometry("520x330")
    dialog.resizable(False, False)
    dialog.configure(bg="#0f172a")  # Dark slate theme

    # Force modal and focus
    dialog.transient(dialog_parent)
    dialog.grab_set()
    dialog.focus_set()

    result: Dict[str, Any] = {
        "confirmed": False,
        "appetite": default_appetite,
        "cash": default_cash,
    }

    # Header
    header_frame = tk.Frame(dialog, bg="#1e293b", padx=16, pady=12)
    header_frame.pack(fill="x")

    tk.Label(
        header_frame,
        text="📊 Daily Investment Parameters",
        font=("Helvetica", 15, "bold"),
        fg="#38bdf8",
        bg="#1e293b",
    ).pack(anchor="w")

    tk.Label(
        header_frame,
        text="Confirm your capital parameters to sync portfolio with Google Drive.",
        font=("Helvetica", 10),
        fg="#94a3b8",
        bg="#1e293b",
    ).pack(anchor="w", pady=(2, 0))

    # Form Fields
    form_frame = tk.Frame(dialog, bg="#0f172a", padx=24, pady=18)
    form_frame.pack(fill="both", expand=True)

    # 1. Current Appetite
    tk.Label(
        form_frame,
        text="Current Appetite (₹):",
        font=("Helvetica", 11, "bold"),
        fg="#f8fafc",
        bg="#0f172a",
    ).grid(row=0, column=0, sticky="w", pady=(0, 4))

    appetite_var = tk.StringVar(value=f"{default_appetite:,.2f}")
    appetite_entry = tk.Entry(
        form_frame,
        textvariable=appetite_var,
        font=("Helvetica", 12),
        bg="#1e293b",
        fg="#f8fafc",
        insertbackground="white",
        relief="flat",
        bd=4,
    )
    appetite_entry.grid(row=1, column=0, sticky="ew", pady=(0, 14))

    # 2. Cash Available
    tk.Label(
        form_frame,
        text="Cash Available for Investment (₹):",
        font=("Helvetica", 11, "bold"),
        fg="#f8fafc",
        bg="#0f172a",
    ).grid(row=2, column=0, sticky="w", pady=(0, 4))

    cash_var = tk.StringVar(value=f"{default_cash:,.2f}")
    cash_entry = tk.Entry(
        form_frame,
        textvariable=cash_var,
        font=("Helvetica", 12),
        bg="#1e293b",
        fg="#f8fafc",
        insertbackground="white",
        relief="flat",
        bd=4,
    )
    cash_entry.grid(row=3, column=0, sticky="ew", pady=(0, 6))

    form_frame.columnconfigure(0, weight=1)

    # Error message label
    err_lbl = tk.Label(
        form_frame,
        text="",
        font=("Helvetica", 9),
        fg="#f87171",
        bg="#0f172a",
    )
    err_lbl.grid(row=4, column=0, sticky="w")

    def _parse_val(raw_str: str) -> Optional[float]:
        cleaned = re.sub(r"[^\d.-]", "", raw_str.strip())
        try:
            val = float(cleaned)
            return val if val >= 0 else None
        except ValueError:
            return None

    def on_confirm():
        app_val = _parse_val(appetite_var.get())
        if app_val is None:
            err_lbl.config(
                text="Please enter a valid positive number for Current Appetite."
            )
            appetite_entry.focus_set()
            return

        c_val = _parse_val(cash_var.get())
        if c_val is None:
            err_lbl.config(
                text="Please enter a valid positive number for Cash Available."
            )
            cash_entry.focus_set()
            return

        result["confirmed"] = True
        result["appetite"] = app_val
        result["cash"] = c_val
        dialog.destroy()

    def on_skip():
        result["confirmed"] = False
        dialog.destroy()

    # Buttons Frame
    btn_frame = tk.Frame(dialog, bg="#0f172a", padx=24, pady=12)
    btn_frame.pack(fill="x", side="bottom")

    skip_btn = tk.Button(
        btn_frame,
        text="Skip Sync",
        font=("Helvetica", 10),
        bg="#334155",
        fg="#cbd5e1",
        activebackground="#475569",
        activeforeground="#ffffff",
        relief="flat",
        padx=14,
        pady=6,
        command=on_skip,
        cursor="hand2",
    )
    skip_btn.pack(side="left")

    confirm_btn = tk.Button(
        btn_frame,
        text="Confirm & Sync with Drive",
        font=("Helvetica", 10, "bold"),
        bg="#0284c7",  # Sky blue button
        fg="#ffffff",
        activebackground="#0369a1",
        activeforeground="#ffffff",
        relief="flat",
        padx=18,
        pady=6,
        command=on_confirm,
        cursor="hand2",
    )
    confirm_btn.pack(side="right")

    dialog.bind("<Return>", lambda e: on_confirm())
    dialog.bind("<Escape>", lambda e: on_skip())

    # Pre-select first entry
    appetite_entry.focus_set()
    appetite_entry.select_range(0, tk.END)

    # Center dialog on screen or parent
    dialog.update_idletasks()
    w, h = dialog.winfo_width(), dialog.winfo_height()
    if parent:
        x = parent.winfo_rootx() + (parent.winfo_width() // 2) - (w // 2)
        y = parent.winfo_rooty() + (parent.winfo_height() // 2) - (h // 2)
    else:
        x = (dialog.winfo_screenwidth() // 2) - (w // 2)
        y = (dialog.winfo_screenheight() // 2) - (h // 2)
    dialog.geometry(f"+{max(0, x)}+{max(0, y)}")

    dialog.wait_window()

    if owns_root:
        try:
            root.destroy()
        except Exception:
            pass

    if result["confirmed"]:
        return result["appetite"], result["cash"]
    return None


