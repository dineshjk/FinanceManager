def get_all_advices(
    db_path: str = STOCK_DB_PATH,
    status_filter: Optional[str] = None,
    search_query: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """
    Fetches all advice log records from SQLite, ordered by advice_date DESC, id_advice DESC.
    Supports optional status filtering and search text filtering.
    """
    ensure_advice_log_table(db_path=db_path)
    if not os.path.exists(db_path):
        return []

    conn = None
    try:
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()

        query = """
            SELECT id_advice, advice_date, advice_text, status,
                   COALESCE(execution_date, '') AS execution_date,
                   COALESCE(notes, '') AS notes
            FROM advice_log
            WHERE advice_text NOT LIKE '%Daily Pick of the Day Recommendation%'
        """
        params: List[Any] = []

        if status_filter and status_filter != "All":
            sf = status_filter.strip()
            if sf == "Pending":
                query += " AND status = 'Pending'"
            elif sf.lower().startswith("fully"):
                query += " AND (status LIKE 'Fully followed%' OR status = 'Fully Followed')"
            elif sf.lower().startswith("partially"):
                query += " AND (status LIKE 'Partially followed%' OR status = 'Partially Followed')"
            elif sf.lower().startswith("not"):
                query += " AND (status = 'Not followed' OR status = 'Not Followed')"
            elif sf.lower() in ("conditional", "to be followed after [condition]") or sf.lower().startswith("to be followed"):
                query += " AND status LIKE 'To be followed after%'"
            elif is_valid_advice_status(sf):
                query += " AND status = ?"
                params.append(sf)

        if search_query and search_query.strip():
            query += " AND (advice_text LIKE ? OR notes LIKE ? OR advice_date LIKE ? OR status LIKE ?)"
            term = f"%{search_query.strip()}%"
            params.extend([term, term, term, term])

        query += " ORDER BY advice_date DESC, id_advice DESC"
        cursor.execute(query, params)
        rows = cursor.fetchall()
        return [dict(r) for r in rows]
    except Exception as e:
        logger.error(f"Error fetching advices from '{db_path}': {e}")
        return []
    finally:
        if conn:
            conn.close()


