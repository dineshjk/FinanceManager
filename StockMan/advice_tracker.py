def _clean_markdown_text(val: str) -> str:
    """Strips markdown formatting, bold/italics, backticks, and escape backslashes."""
    if not val:
        return ""
    # Unescape characters commonly backslash-escaped in markdown (e.g. \~, \₹, \$, \*)
    cleaned = re.sub(r"\\([~*_\`₹\$])", r"\1", val)
    cleaned = re.sub(r"[*_~`]", "", cleaned)
    cleaned = re.sub(r"[ \t]+", " ", cleaned)
    return cleaned.strip()


def extract_machine_advice_table(report_text: str) -> Optional[str]:
    """
    Searches report_text for exact delimiter tags [BEGIN_MACHINE_ADVICE] and [END_MACHINE_ADVICE].
    Tolerates common markdown escaping variations like \\[BEGIN\\_MACHINE\\_ADVICE\\] and
    closing tags embedded within markdown table rows.
    Returns ONLY the markdown table found between these tags, or None if tags are absent.
    """
    if not report_text:
        return None
    pattern = r"(?:\\?\[|\b)BEGIN\\?_MACHINE\\?_ADVICE(?:\\?\]|\b)([\s\S]*?)(?:\\?\[|\b)END\\?_MACHINE\\?_ADVICE(?:\\?\]|\b)"
    m = re.search(pattern, report_text, re.IGNORECASE)
    if m:
        raw = m.group(1).strip()
        raw = re.sub(r"\|\s*$", "", raw).strip()
        return raw
    return None


def parse_machine_advice_rows(
    table_text: str, fallback_date: Optional[str] = None
) -> List[Dict[str, Any]]:
    """
    Parses a markdown table from the machine advice block into structured advice dicts.
    Extracts Date, Ticker, Action, Quantity, Target_Price, Status, Condition, Notes.
    """
    if not table_text:
        return []

    lines = [ln.strip() for ln in table_text.splitlines() if ln.strip().startswith("|")]
    if len(lines) < 2:
        return []

    # Header line
    raw_headers = [_clean_markdown_text(c).lower().replace(" ", "_") for c in lines[0].split("|")[1:-1]]

    header_map = {}
    for idx, h in enumerate(raw_headers):
        if any(k in h for k in ("date",)):
            header_map["date"] = idx
        elif any(k in h for k in ("ticker", "stock", "symbol", "code")):
            header_map["ticker"] = idx
        elif any(k in h for k in ("action", "trade_action", "type")):
            header_map["action"] = idx
        elif any(k in h for k in ("qty", "quantity", "shares")):
            header_map["quantity"] = idx
        elif any(k in h for k in ("target", "cmp", "price")):
            header_map["target_price"] = idx
        elif any(k in h for k in ("status", "trade_status")):
            header_map["status"] = idx
        elif any(k in h for k in ("condition",)):
            header_map["condition"] = idx
        elif any(k in h for k in ("note", "rationale")):
            header_map["notes"] = idx

    results = []
    start_idx = 1
    if len(lines) > 1 and ("---" in lines[1] or ":-" in lines[1]):
        start_idx = 2

    for row_line in lines[start_idx:]:
        cols = [_clean_markdown_text(c) for c in row_line.split("|")[1:-1]]
        if not cols or all(not c for c in cols):
            continue

        def _get_val(key: str, default: str = "") -> str:
            idx = header_map.get(key)
            if idx is not None and idx < len(cols):
                return cols[idx].strip()
            return default

        row_date = _get_val("date")
        if not is_valid_iso_date(row_date):
            row_date = fallback_date or date.today().isoformat()

        ticker = _get_val("ticker").upper()
        action = _get_val("action").upper()
        raw_qty = _get_val("quantity")
        target_price = _get_val("target_price")
        raw_status = _get_val("status") or DEFAULT_STATUS
        condition = _get_val("condition")
        notes = _get_val("notes")

        qty_num = None
        if raw_qty:
            qty_m = re.search(r"(\d+(?:\.\d+)?)", raw_qty.replace(",", ""))
            if qty_m:
                try:
                    qty_num = float(qty_m.group(1))
                except ValueError:
                    qty_num = None

        # Build clean actionable advice text
        advice_parts = []
        if action:
            advice_parts.append(action)
        if raw_qty:
            advice_parts.append(f"{raw_qty} shares of" if not raw_qty.lower().endswith("shares") else raw_qty)
        if ticker:
            advice_parts.append(ticker)
        if target_price:
            advice_parts.append(f"at {target_price}")

        adv_text = " ".join(advice_parts).strip()
        if not adv_text and ticker:
            adv_text = f"Action on {ticker}"

        status_val = raw_status.strip() if raw_status else DEFAULT_STATUS
        if condition and "To be followed after" not in status_val:
            if status_val.lower() == "conditional" or "condition" in status_val.lower():
                status_val = f"To be followed after [{condition}]"

        results.append({
            "advice_date": row_date,
            "advice_text": adv_text,
            "winner": ticker,
            "rebalancing_strategy": "",
            "action": action,
            "ticker": ticker,
            "quantity": qty_num,
            "target_price": target_price,
            "status": status_val,
            "condition": condition,
            "notes": notes,
        })

    return results


def parse_advice_from_pick_of_the_day(
    report_text: str, filename_hint: Optional[str] = None
) -> Dict[str, Any]:
    """
    Parses a daily Pick of the Day intelligence markdown report.
    Task 1 Requirement:
      Searches for strict delimiter tags [BEGIN_MACHINE_ADVICE] and [END_MACHINE_ADVICE].
      Extracts ONLY the markdown table found between these tags.
      Ignores all other tables (Sector Balance, Brokerage Consensus, Full Portfolio) and conversational text.
    """
    if not report_text:
        return {
            "advice_date": date.today().isoformat(),
            "advice_text": "",
            "winner": "",
            "rebalancing_strategy": "",
            "action": "",
            "ticker": "",
            "notes": "",
            "status": DEFAULT_STATUS,
            "all_advices": [],
        }

    # 1. Extract Date from header/filename
    date_match = re.search(r"\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})", report_text, re.IGNORECASE)
    if not date_match:
        date_match = re.search(r"Date:\s*(\d{4}-\d{2}-\d{2})", report_text, re.IGNORECASE)
    if not date_match:
        date_match = re.search(r"#.*?\b(\d{4}-\d{2}-\d{2})\b", report_text)
    if not date_match:
        compact_m = re.search(r"#.*?\b(\d{4})(\d{2})(\d{2})\b", report_text)
        if compact_m:
            extracted_date = f"{compact_m.group(1)}-{compact_m.group(2)}-{compact_m.group(3)}"
        elif filename_hint:
            fn_iso = re.search(r"(\d{4})[-_](\d{2})[-_](\d{2})", filename_hint)
            if fn_iso:
                extracted_date = f"{fn_iso.group(1)}-{fn_iso.group(2)}-{fn_iso.group(3)}"
            else:
                fn_compact = re.search(r"(\d{4})(\d{2})(\d{2})", filename_hint)
                if fn_compact:
                    extracted_date = f"{fn_compact.group(1)}-{fn_compact.group(2)}-{fn_compact.group(3)}"
                else:
                    extracted_date = date.today().isoformat()
        else:
            extracted_date = date.today().isoformat()
    else:
        extracted_date = date_match.group(1)

    # 2. Extract strictly from [BEGIN_MACHINE_ADVICE] and [END_MACHINE_ADVICE]
    machine_table = extract_machine_advice_table(report_text)
    if machine_table:
        advices = parse_machine_advice_rows(machine_table, fallback_date=extracted_date)
        if advices:
            primary = dict(advices[0])
            primary["all_advices"] = advices
            return primary

    # 3. Fallback to ADVICE_LOG_EXPORT table if strict delimiter tags are absent
    export_table_m = re.search(
        r"###\s*ADVICE[\\_]+LOG[\\_]+EXPORT[^\n]*\n+([\s\S]*?)(?:\n##|\Z)",
        report_text,
        re.IGNORECASE,
    )
    if export_table_m:
        advices = parse_machine_advice_rows(export_table_m.group(1), fallback_date=extracted_date)
        if advices:
            primary = dict(advices[0])
            primary["all_advices"] = advices
            return primary

    # 4. Fallback for legacy tests: check explicit Action: and Winner:
    # Strictly ignore all other tables (Sector Balance, Brokerage, Full Portfolio tables)
    winner_match = re.search(r"\*\*Winner:\*\*\s*([^\n*]+)", report_text, re.IGNORECASE)
    if not winner_match:
        winner_match = re.search(r"Winner:\s*([^\n*]+)", report_text, re.IGNORECASE)
    winner_str = winner_match.group(1).strip() if winner_match else ""

    rebal_match = re.search(
        r"(?:\*?Rebalancing Strategy:\*?|\bRebalancing Strategy:\s*)([^\n\r]+)",
        report_text,
        re.IGNORECASE,
    )
    rebalancing_strategy = _clean_markdown_text(rebal_match.group(1)) if rebal_match else ""

    action_match = re.search(
        r"(?:-\s*Action:\s*|\bAction:\s*)([^\n\r]+)", report_text, re.IGNORECASE
    )
    action_str = _clean_markdown_text(action_match.group(1)) if action_match else ""

    extracted_ticker = ""
    if winner_str:
        ticker_m = re.search(r"\(([A-Z0-9_\.\-]+)\)", winner_str)
        if ticker_m:
            extracted_ticker = ticker_m.group(1).strip()
    if not extracted_ticker and action_str:
        ticker_m = re.search(r"\b([A-Z]{3,15})\b", action_str)
        if ticker_m and ticker_m.group(1) not in ("BUY", "ADD", "SELL", "TRIM", "CMP", "INR", "KEEP", "HOLD"):
            extracted_ticker = ticker_m.group(1).strip()
    if not extracted_ticker and rebalancing_strategy:
        ticker_m = re.search(r"\(([A-Z0-9_\.\-]+)\)", rebalancing_strategy)
        if ticker_m:
            extracted_ticker = ticker_m.group(1).strip()

    if action_str and rebalancing_strategy:
        advice_text = f"{action_str} — Rebalancing Strategy: {rebalancing_strategy}"
    elif action_str:
        advice_text = action_str
    elif rebalancing_strategy:
        advice_text = f"Rebalancing Strategy: {rebalancing_strategy}"
    elif winner_str:
        clean_winner = _clean_markdown_text(winner_str)
        advice_text = f"Buy Winner: {clean_winner}"
    else:
        # DO NOT fall back to other tables or "Daily Pick of the Day Recommendation"
        advice_text = ""

    notes_parts = []
    if rebalancing_strategy:
        notes_parts.append(f"Rebalancing Strategy: {rebalancing_strategy}")
    notes = " | ".join(notes_parts)

    primary = {
        "advice_date": extracted_date,
        "advice_text": advice_text,
        "winner": winner_str,
        "rebalancing_strategy": rebalancing_strategy,
        "action": action_str,
        "ticker": extracted_ticker,
        "notes": notes,
        "status": DEFAULT_STATUS if advice_text else "",
        "all_advices": [],
    }
    if advice_text:
        primary["all_advices"] = [primary]
    return primary


def get_latest_pick_advice() -> Optional[Dict[str, Any]]:
    """
    Reads the latest local Pick of the Day report and parses its advice.
    Returns dict with keys ('advice_date', 'advice_text', 'winner', 'rebalancing_strategy', 'source_file') or None.
    """
    from StockMan.drive_sync import get_local_pick_of_the_day

    res = get_local_pick_of_the_day()
    if not res:
        return None
    content, filename, mtime = res
    parsed = parse_advice_from_pick_of_the_day(content)
    parsed["source_file"] = filename
    parsed["mtime"] = mtime
    return parsed


def auto_update_advice_from_pick_of_the_day(
    report_text_or_path: Optional[str] = None,
    db_path: str = STOCK_DB_PATH,
    excel_path: Optional[str] = None,
    trigger_drive_upload: bool = False,
    update_excel: bool = True,
) -> Optional[Dict[str, Any]]:
    """
    Automates parsing and syncing advice from Pick of the Day into:
      1. SQLite table 'advice_log' (deduplicating against existing entries).
      2. 'StockMan_Portfolio.xlsx' (sheet 'Advice_Log').
      3. Google Drive (if trigger_drive_upload is True).
    Returns result dictionary or None.
    """
    from StockMan.drive_sync import PORTFOLIO_EXCEL_PATH, get_local_pick_of_the_day, update_portfolio_excel

    target_excel = excel_path or PORTFOLIO_EXCEL_PATH
    content = None
    source_name = ""

    if report_text_or_path is None:
        local_res = get_local_pick_of_the_day()
        if not local_res:
            logger.info("auto_update_advice_from_pick_of_the_day: No local Pick of the Day report found.")
            return None
        content, source_name, _ = local_res
    elif isinstance(report_text_or_path, str) and os.path.isfile(report_text_or_path):
        source_name = os.path.basename(report_text_or_path)
        with open(report_text_or_path, "r", encoding="utf-8") as f_in:
            content = f_in.read()
    else:
        content = str(report_text_or_path)
        source_name = "Direct Content"

    parsed = parse_advice_from_pick_of_the_day(content, filename_hint=source_name)
    all_advices = parsed.get("all_advices") or ([parsed] if parsed.get("advice_text") else [])
    # Filter out placeholder advice strings
    all_advices = [
        a for a in all_advices
        if a.get("advice_text") and "Daily Pick of the Day Recommendation" not in a.get("advice_text")
    ]
    if not all_advices:
        return None

    adv_date = parsed.get("advice_date")
    adv_text = all_advices[0].get("advice_text")

    # Determine notes
    base_notes = parsed.get("notes") or ""
    if source_name and source_name != "Direct Content":
        src_tag = f"Source: {source_name}"
        if src_tag not in base_notes:
            notes = f"{base_notes} | {src_tag}".strip(" |")
        else:
            notes = base_notes
    else:
        notes = base_notes

    ensure_advice_log_table(db_path=db_path)
    conn = None
    advice_id = None
    is_new = False
    is_updated = False

    try:
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()

        for adv_item in all_advices:
            cur_item_text = adv_item.get("advice_text", "").strip()
            cur_item_date = adv_item.get("advice_date", adv_date)
            cur_item_ticker = adv_item.get("ticker", "").upper()
            cur_item_status = adv_item.get("status") or DEFAULT_STATUS
            cur_item_notes = adv_item.get("notes") or notes
            cur_item_exec_date = None
            m_dt = re.search(r"\b(\d{4}-\d{2}-\d{2})\b", cur_item_status)
            if m_dt and is_valid_iso_date(m_dt.group(1)):
                cur_item_exec_date = m_dt.group(1)

            # Check existing entries for this date
            cur.execute(
                """
                SELECT id_advice, advice_date, advice_text, status, execution_date, notes
                FROM advice_log
                WHERE advice_date = ?
                ORDER BY id_advice ASC
                """,
                (cur_item_date,),
            )
            existing_rows = cur.fetchall()

            matched_row = None
            reb_strat = adv_item.get("rebalancing_strategy", "")

            for row in existing_rows:
                r_text = (row["advice_text"] or "").upper()
                if cur_item_ticker and len(cur_item_ticker) >= 3 and cur_item_ticker in r_text:
                    matched_row = row
                    break
                if cur_item_text[:35].lower() in (row["advice_text"] or "").lower():
                    matched_row = row
                    break
                if (row["advice_text"] or "")[:35].lower() in cur_item_text.lower():
                    matched_row = row
                    break
                # If existing row was just a WAIT/WATCH fallback, upgrade it to the machine advice
                if r_text.startswith("WAIT/WATCH") and cur_item_ticker:
                    matched_row = row
                    break

            if matched_row:
                advice_id = matched_row["id_advice"]
                cur_adv_text = matched_row["advice_text"] or ""
                cur_db_notes = matched_row["notes"] or ""

                is_wait_watch = cur_adv_text.upper().startswith("WAIT/WATCH") and cur_item_ticker
                should_update_text = (
                    is_wait_watch
                    or (
                        reb_strat
                        and reb_strat not in cur_adv_text
                        and "Rebalancing Strategy" not in cur_adv_text
                    )
                )
                should_update_notes = is_wait_watch or (reb_strat and reb_strat not in cur_db_notes)

                if should_update_text or should_update_notes:
                    new_text = cur_item_text if should_update_text else cur_adv_text
                    new_notes = cur_item_notes if is_wait_watch else (cur_item_notes if should_update_notes else cur_db_notes)
                    new_status = cur_item_status if is_wait_watch else matched_row["status"]
                    if should_update_notes and cur_db_notes and reb_strat not in cur_db_notes and not is_wait_watch:
                        new_notes = f"{cur_db_notes} | Rebalancing Strategy: {reb_strat}"

                    cur.execute(
                        """
                        UPDATE advice_log
                        SET advice_text = ?, status = ?, notes = ?
                        WHERE id_advice = ?
                        """,
                        (new_text, new_status, new_notes, advice_id),
                    )
                    conn.commit()
                    is_updated = True
                    logger.info(f"Updated advice #{advice_id}: '{new_text}' ({new_status})")
            else:
                # Insert new advice with specified or default status
                cur.execute(
                    """
                    INSERT INTO advice_log (advice_date, advice_text, status, execution_date, notes)
                    VALUES (?, ?, ?, ?, ?)
                    """,
                    (cur_item_date, cur_item_text, cur_item_status, cur_item_exec_date, cur_item_notes),
                )
                conn.commit()
                advice_id = cur.lastrowid
                is_new = True
                logger.info(f"Auto-logged advice #{advice_id} for {cur_item_date}: '{cur_item_text[:60]}...' ({cur_item_status})")
    except Exception as e:
        logger.error(f"Error in auto_update_advice_from_pick_of_the_day: {e}", exc_info=True)
        return None
    finally:
        if conn:
            conn.close()

    # Regenerate StockMan_Portfolio.xlsx
    excel_result_path = target_excel
    if update_excel:
        try:
            excel_result_path = update_portfolio_excel(excel_path=target_excel, db_path=db_path)
        except Exception as ex_err:
            logger.error(f"Failed to regenerate '{target_excel}' during auto advice update: {ex_err}")

    # Optional Google Drive background upload
    if trigger_drive_upload:
        try:
            from StockMan.drive_sync import (
                GOOGLE_DRIVE_AVAILABLE,
                get_credentials_file,
                get_drive_service,
                upload_portfolio_to_drive,
            )
            if GOOGLE_DRIVE_AVAILABLE and get_credentials_file():
                import threading
                def _bg_up():
                    try:
                        svc = get_drive_service()
                        upload_portfolio_to_drive(svc, file_path=excel_result_path)
                    except Exception as u_err:
                        logger.warning(f"Background upload after auto advice update failed: {u_err}")
                threading.Thread(target=_bg_up, daemon=True).start()
        except Exception as e:
            logger.debug(f"Drive upload check failed: {e}")

    return {
        "advice_id": advice_id,
        "advice_date": adv_date,
        "advice_text": adv_text,
        "is_new": is_new,
        "is_updated": is_updated,
        "excel_path": excel_result_path,
        "source_file": source_name,
    }


def sync_all_pending_pick_of_the_day_advices(
    search_dirs: Optional[List[str]] = None,
    db_path: str = STOCK_DB_PATH,
    excel_path: Optional[str] = None,
    trigger_drive_upload: bool = False,
) -> List[Dict[str, Any]]:
    """
    Scans all Pick_of_the_day_*.md files on disk,
    checks if each report's advice is already in SQLite advice_log,
    auto-imports missing advice, and refreshes StockMan_Portfolio.xlsx.
    """
    from StockMan.drive_sync import DATA_DIR, PORTFOLIO_EXCEL_PATH, PROJECT_ROOT, update_portfolio_excel

    target_excel = excel_path or PORTFOLIO_EXCEL_PATH
    if search_dirs is None:
        search_dirs = [DATA_DIR]
        if os.path.abspath(DATA_DIR) != os.path.abspath(PROJECT_ROOT):
            search_dirs.append(PROJECT_ROOT)

    files_to_process = []
    seen_basenames = set()

    for s_dir in search_dirs:
        if not os.path.isdir(s_dir):
            continue
        for pat in ("Pick_of_the_day_*.md", "Pick_of_the_day_*.txt"):
            for f_path in glob.glob(os.path.join(s_dir, pat)):
                bname = os.path.basename(f_path)
                # Ignore alias/mirror and documentation templates
                if "latest" in bname.lower() or "doc" in bname.lower():
                    continue
                if bname in seen_basenames:
                    continue
                seen_basenames.add(bname)
                files_to_process.append(f_path)

    # Sort files chronologically by date in filename or mtime
    def _file_sort_key(p):
        fname = os.path.basename(p)
        dt_m = re.search(r"(\d{4})[-_]?(\d{2})[-_]?(\d{2})", fname)
        if dt_m:
            return f"{dt_m.group(1)}-{dt_m.group(2)}-{dt_m.group(3)}"
        return datetime.fromtimestamp(os.path.getmtime(p)).date().isoformat()

    files_to_process.sort(key=_file_sort_key)

    results = []
    any_change = False

    for fp in files_to_process:
        try:
            res = auto_update_advice_from_pick_of_the_day(
                report_text_or_path=fp,
                db_path=db_path,
                excel_path=target_excel,
                trigger_drive_upload=False,
                update_excel=False,
            )
            if res:
                results.append(res)
                if res.get("is_new") or res.get("is_updated"):
                    any_change = True
        except Exception as err:
            logger.warning(f"Error processing '{fp}' in sync_all_pending_pick_of_the_day_advices: {err}")

    # Ensure Excel is refreshed once if changes were made
    if any_change:
        try:
            update_portfolio_excel(excel_path=target_excel, db_path=db_path, sync_advice=False)
            logger.info(f"sync_all_pending_pick_of_the_day_advices: Refreshed '{target_excel}'.")
        except Exception as ex:
            logger.error(f"Failed to refresh Excel after batch advice sync: {ex}")

        if trigger_drive_upload:
            try:
                from StockMan.drive_sync import (
                    GOOGLE_DRIVE_AVAILABLE,
                    get_credentials_file,
                    get_drive_service,
                    upload_portfolio_to_drive,
                )
                if GOOGLE_DRIVE_AVAILABLE and get_credentials_file():
                    import threading
                    def _bg_up():
                        try:
                            svc = get_drive_service()
                            upload_portfolio_to_drive(svc, file_path=target_excel)
                        except Exception as u_err:
                            logger.warning(f"Background upload after batch advice sync failed: {u_err}")
                    threading.Thread(target=_bg_up, daemon=True).start()
            except Exception as e:
                logger.debug(f"Drive upload check failed: {e}")

    return results


