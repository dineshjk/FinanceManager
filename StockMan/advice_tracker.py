def extract_trade_details_from_advice(advice_text: str) -> Dict[str, Any]:
    """
    Extracts action, ticker, quantity, price, and net amount from an advice text string.
    """
    res = {
        "action": "BUY",
        "ticker": "",
        "quantity": 0.0,
        "price": 0.0,
        "net_amt": 0.0,
    }
    if not advice_text:
        return res

    text_upper = advice_text.upper()

    # Determine action
    if any(k in text_upper for k in ("SELL", "TRIM", "EXIT", "REDUCE", "LIQUIDATE")):
        res["action"] = "SELL"
    else:
        res["action"] = "BUY"

    # Extract quantity
    qty_m = re.search(r"\b(?:buy|add|trim|sell|exit|reduce)?\s*[:=]?\s*(\d+(?:,\d+)?(?:\.\d+)?)\s*(?:shares|qty|stocks)?\b", advice_text, re.IGNORECASE)
    if not qty_m or float(qty_m.group(1).replace(",", "")) == 0:
        qty_m = re.search(r"\b(\d+(?:,\d+)?)\s*(?:shares|qty|stocks)\b", advice_text, re.IGNORECASE)
    if qty_m:
        try:
            res["quantity"] = float(qty_m.group(1).replace(",", ""))
        except ValueError:
            pass

    # Extract ticker
    ticker_m = re.search(r"\(([A-Z0-9_\.\-]+)\)", advice_text)
    if ticker_m:
        res["ticker"] = ticker_m.group(1).strip()
    else:
        words = re.findall(r"\b[A-Z]{3,15}\b", advice_text)
        ignored = {"BUY", "SELL", "ADD", "TRIM", "EXIT", "HOLD", "CMP", "INR", "THE", "AND", "FOR", "WITH", "NOT", "AFTER", "WAIT", "WATCH"}
        for w in words:
            if w not in ignored:
                res["ticker"] = w
                break

    # Extract price / CMP
    price_m = re.search(r"(?:at\s+cmp|cmp|target|price|at|@)[\s\(:=~₹\$]*([0-9,]+(?:\.[0-9]+)?)", advice_text, re.IGNORECASE)
    if price_m:
        try:
            res["price"] = float(price_m.group(1).replace(",", ""))
        except ValueError:
            pass

    # Extract explicit allocation if present
    alloc_m = re.search(r"allocation\s*[:=~₹\$\s]*([0-9,]+(?:\.[0-9]+)?)", advice_text, re.IGNORECASE)
    if alloc_m:
        try:
            res["net_amt"] = float(alloc_m.group(1).replace(",", ""))
        except ValueError:
            pass

    if res["net_amt"] == 0.0 and res["quantity"] > 0 and res["price"] > 0:
        res["net_amt"] = round(res["quantity"] * res["price"], 2)

    return res


def execute_advice_ledger_update(
    advice_id: int,
    actual_qty: Optional[float] = None,
    execution_date: Optional[str] = None,
    executed_price: Optional[float] = None,
    db_path: str = STOCK_DB_PATH,
    excel_path: Optional[str] = None,
    parent_win: Optional[Any] = None,
) -> Dict[str, Any]:
    """
    Executes ledger update and adjusts cash for an advice item:
      - Deducts cash for BUY trades
      - Adds cash for SELL trades
      - Refreshes StockMan_Portfolio.xlsx
    """
    rec = get_advice_by_id(advice_id, db_path=db_path)
    if not rec:
        return {"success": False, "error": f"Advice #{advice_id} not found."}

    adv_text = rec["advice_text"]
    details = extract_trade_details_from_advice(adv_text)
    action = details["action"]
    ticker = details["ticker"]
    qty = actual_qty if (actual_qty is not None and actual_qty > 0) else details["quantity"]
    price = executed_price if (executed_price is not None and executed_price > 0) else details["price"]
    exec_dt = execution_date or rec.get("execution_date") or date.today().isoformat()

    if qty <= 0 and parent_win:
        try:
            from tkinter import simpledialog
            user_q = simpledialog.askinteger(
                "Quantity",
                f"Advice: '{adv_text}'\n\nEnter execution quantity:",
                initialvalue=1,
                minvalue=1,
                parent=parent_win,
            )
            if user_q:
                qty = float(user_q)
        except Exception:
            qty = 1.0

    if price <= 0:
        try:
            conn = sqlite3.connect(db_path)
            c = conn.cursor()
            c.execute("SELECT curr_avg_price FROM stocks WHERE stk_code = ? OR ticker LIKE ?", (ticker, f"{ticker}%"))
            p_row = c.fetchone()
            if p_row and p_row[0]:
                price = float(p_row[0])
            conn.close()
        except Exception:
            pass

    if price <= 0 and parent_win:
        try:
            from tkinter import simpledialog
            user_p = simpledialog.askfloat(
                "Price",
                f"Enter execution price per share for {ticker or 'stock'}:",
                initialvalue=100.0,
                minvalue=0.1,
                parent=parent_win,
            )
            if user_p:
                price = float(user_p)
        except Exception:
            price = 0.0

    net_amt = round(qty * price, 2) if (qty > 0 and price > 0) else details["net_amt"]

    try:
        from StockMan.drive_sync import adjust_cash_for_trades
        trade_dict = {
            "stk_code": ticker or "STOCK",
            "company_name": ticker or "Company",
            "trade_type_trd": action,
            "qty_trd": qty,
            "net_amt_trd": net_amt,
            "trd_dt": exec_dt,
        }
        new_cash, appetite, out_excel = adjust_cash_for_trades(
            [trade_dict],
            excel_path=excel_path,
            db_path=db_path,
            trigger_drive_upload=False,
        )
        return {
            "success": True,
            "action": action,
            "ticker": ticker,
            "qty": qty,
            "price": price,
            "net_amt": net_amt,
            "new_cash": new_cash,
            "excel_path": out_excel,
        }
    except Exception as ex:
        logger.error(f"execute_advice_ledger_update failed: {ex}")
        return {"success": False, "error": str(ex)}


