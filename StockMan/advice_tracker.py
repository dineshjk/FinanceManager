    # ToolTip helper for hovering over conditional rows
    class TreeToolTip:
        def __init__(self, widget):
            self.widget = widget
            self.tip_window = None

        def show_tip(self, text, x, y):
            if self.tip_window or not text:
                return
            self.tip_window = tw = tk.Toplevel(self.widget)
            tw.wm_overrideredirect(True)
            tw.wm_geometry(f"+{x+15}+{y+15}")
            lbl = tk.Label(
                tw,
                text=text,
                justify=tk.LEFT,
                background="#1e1e2e",
                foreground="#f5c2e7",
                relief=tk.SOLID,
                borderwidth=1,
                font=("Helvetica", 9, "bold"),
                padx=8,
                pady=4,
            )
            lbl.pack()

        def hide_tip(self):
            if self.tip_window:
                try:
                    self.tip_window.destroy()
                except Exception:
                    pass
                self.tip_window = None

    tree_tooltip = TreeToolTip(tree)

