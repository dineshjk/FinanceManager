"""
Advice Tracking, AI Report Ingestion, & Execution Management for StockMan.

This module provides end-to-end management for investment recommendations generated by
the Google Gemini AI engine. It records advice into the SQLite `advice_log` table,
tracks execution states ('Fully Followed', 'Partially Followed', 'Not Followed'),
automatically correlates executed trades with open recommendations, and exports a
consolidated dual-sheet workbook ('StockMan_Portfolio.xlsx') synchronized to Google Drive.

Key Responsibilities:
    • Database Persistence: Manages CRUD operations for the `advice_log` table including
      fields for advice date, ticker, company name, recommended action (BUY/SELL), target
      price range, recommended quantity, reasoning, status, and actual execution date.
    • Pick of the Day Parser: Automatically parses structured text outputs from Gemini LLM
      advice prompts and extracts actionable trade parameters.
    • Automatic Trade Matching: Intercepts newly saved trades from `trade_add.py` or
      `trade_add_zerodha.py`, searches for matching open recommendations on the same ticker,
      and marks them as 'Fully Followed' (or 'Partially Followed') with the trade execution date.
    • Excel Export Integration: Generates 'StockMan_Portfolio.xlsx' featuring both active
      portfolio holdings and the complete advice audit trail, triggering asynchronous
      upload to Google Drive via `StockMan.drive_sync`.

Key Functions:
    • `show_advice_tracker(parent)`: Spawns the main Tkinter Advice Tracker UI window.
    • `match_open_advice_with_trade(ticker, action, quantity, trade_date)`: Automated trade matcher.
    • `export_portfolio_with_advice_excel()`: Generates the dual-sheet portfolio Excel workbook.
    • `save_advice_log_entry(...)`: Commits new recommendation records to SQLite.
    • `update_advice_status(advice_id, new_status, execution_date)`: Updates execution state.
"""

