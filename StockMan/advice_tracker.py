def is_valid_advice_status(status: str) -> bool:
    """
    Validates that status matches one of the allowable vocabulary terms:
      - 'Pending'
      - 'Fully followed on YYYY-MM-DD' (or legacy 'Fully Followed')
      - 'Partially followed on YYYY-MM-DD' (or legacy 'Partially Followed')
      - 'Not followed' (or legacy 'Not Followed')
      - 'To be followed after [Condition]' (or 'To be followed after <cond>')
    """
    if not status or not isinstance(status, str):
        return False
    s = status.strip()
    if s in ("Pending", "Not followed", "Not Followed", "Fully Followed", "Partially Followed"):
        return True
    if re.match(r"^Fully\s+followed\s+on\s+\d{4}-\d{2}-\d{2}$", s, re.IGNORECASE):
        return True
    if re.match(r"^Partially\s+followed\s+on\s+\d{4}-\d{2}-\d{2}$", s, re.IGNORECASE):
        return True
    if re.match(r"^To\s+be\s+followed\s+after", s, re.IGNORECASE):
        return True
    return False


def extract_condition_from_status(status: str) -> Optional[str]:
    """Extracts condition string from 'To be followed after [Condition]'."""
    if not status or not isinstance(status, str):
        return None
    m = re.match(r"^To\s+be\s+followed\s+after\s*\[?(.*?)\]?$", status.strip(), re.IGNORECASE)
    if m:
        c = m.group(1).strip().strip("[]")
        return c if c else None
    return None


